-- ============================================================
-- 経理層：キャッシュレス売上の行を「使わない」にする
-- ============================================================
-- 手羽屋の売上は現時点で全額が現金のため、
-- 「売上・キャッシュレス（PayPay等）」の行は使わない設定にする。
--
-- 行そのものは消さない（is_active = false にするだけ）。
-- 理由：将来 PayPay 等を導入したときに、この行を有効に戻すだけで済むから。
--       消してしまうと、そのとき勘定科目と税区分を決め直すことになる。

update public.keiri_account_mapping
set
  is_active = false,
  note = '現時点では手羽屋の売上は全額が現金のため使用しない（2026-08 確認）。'
         'キャッシュレス決済を導入したら is_active を true に戻して使う。',
  updated_at = now()
where business_type_code = 'tebaya'
  and source_type = 'sales_cashless';
