-- ============================================================
-- 現場の立替（keiri_advance_expenses）に「どの店のものか」の印を足す
-- 作成：2026-09-24（司令室B・kp126）
-- ============================================================
-- ■ いまどうなっているか（なぜ要るのか）
--   経理パッケージには「自分のお金で先に払った分を、その場でスマホから記録する」
--   画面（/keiri/advances）が入っています。月15,000円に含まれるものの1つです。
--
--   ところが、この棚には「どの店のものか」の欄がありません。
--   絞りようが無いので、2026-09-24 にひとまず
--   **申し込んだお店にはこの画面を開かない**という門を掛けました。
--   ＝ お金を払ったお店は、いま **この機能をまったく使えません。**
--
--   欄を1つ足せば、ふつうに店ごとに分けて使えるようになります。
--
-- ■ この SQL が何をするか（やさしい説明）
--   立替の棚に「どの店のものか」を書く欄（tenant_id）を1つ足すだけです。
--   ※ **いまある立替の記録は1行も書き換えません。**
--
-- ■ 手羽屋はどうなるか
--   手羽屋は「印が空（null）のお店」です。いまある行はすべて空なので、
--   画面が「印が空のものだけ」に絞っても、**見えるものはいまと同じ**です。
--   これから手羽屋が登録する行も、印は空のままです。
--
-- ■ 実行する前でも、アプリは壊れません（ここが前回までと違うところ）
--   日報の印を足したとき（keiri_tenant_scope.sql）は
--   「SQL を先に実行してから、アプリを本番に出すこと」という順番の縛りがありました。
--   今回は **アプリ側が「欄があるかどうか」を自分で見て、無ければ今までどおりに動く**
--   ように作ってあります（lib/keiri/advanceScope.ts）。
--   ＝ この SQL を実行していない間は、これまでどおり
--      「手羽屋だけが使える／申し込んだお店には門」のままです。
--      実行した瞬間から、申し込んだお店も自分のぶんだけ使えるようになります。
--      **アプリを出し直す必要はありません。**
--
-- ■ 実行しても安全か
--   何度実行しても同じ結果です（add column if not exists / create index if not exists）。
--   既存の表・列・決まりは1つも外していません。足しているだけです。
--   手羽屋の日報・シフト・レジ・LINE・お金の計算には一切触れていません。
--
-- 適用方法:
--   Supabase ダッシュボード（vtuyebyjbvjmucqpkxug）の SQL Editor で1回実行する。
-- ============================================================

-- ------------------------------------------------------------------
-- 1. 立替の棚に「どの店か」の印を足す
--    空（null）＝ 手羽屋。値が入っていれば、経理パッケージを申し込んだお店。
-- ------------------------------------------------------------------
alter table public.keiri_advance_expenses
  add column if not exists tenant_id uuid references public.keiri_tenants (id);

comment on column public.keiri_advance_expenses.tenant_id is
  'どの店の立替か。空（null）＝手羽屋。値＝keiri_tenants.id。既存の行はすべて空のまま。';

-- 「そのお店の、その期間ぶん」を素早く引けるようにする（速さのためだけ・意味は変えない）
create index if not exists keiri_advance_expenses_tenant_date_idx
  on public.keiri_advance_expenses (tenant_id, expense_date desc);

