-- ============================================================
-- 日報に「集計から外す」スイッチを足す
-- ============================================================
-- ■ なぜ必要か
--   ふだんと条件がまるで違う日（2人体制・初日のご祝儀・イベント同時開催など）が
--   1件あるだけで、その出店先の平均売上が引き上がり、ランクや目標額が
--   実力より高く付いてしまう。かといって日報を消すと、売上そのものが
--   帳簿から消えてしまう（お金の記録としては正しく残さないといけない）。
--   そこで **「お金の記録には残すが、出店先の平均・ランクの判定からは外す」**
--   スイッチを用意する。
--
-- ■ どこに効くか（ここが大事）
--   効く  ：出店先ごとの平均売上・出店回数・ランクの自動判定（/analytics・ランク判定）
--   効かない：月次の売上集計・現金まわり・経理層（お金の金額は一切変えない）
--   → 売上を無かったことにするスイッチではない。
--
-- ■ 使い方
--   管理者ページの日報一覧 →「編集」→「この日報を集計から外す」にチェック。

alter table public.daily_reports
  add column if not exists exclude_from_stats boolean not null default false;

comment on column public.daily_reports.exclude_from_stats is
  'true のとき、出店先ごとの平均売上・出店回数・ランク自動判定の対象から外す。売上そのもの（月次集計・経理）には影響しない。';

create index if not exists idx_daily_reports_exclude_from_stats
  on public.daily_reports (exclude_from_stats);
