/**
 * 「いま本番に出ているのは、どの版か」を1つの合言葉にして持たせる。
 *
 * ■ なぜ要るか（2026-09-19）
 *   この日だけで3回、「本番に出したのに古いままに見える」という報告が出て、
 *   そのたびに最優先の仕事が1つ立ち、送るのを止めた。
 *   3回とも原因は同じで、**外からページを読む道具が、同じURLの古い中身を
 *   おぼえていた**（本番は正しかった）。
 *   人が目で「3,000円が出ている／いない」を数えて確かめる限り、これは何度でも起きる。
 *
 * ■ どう解決するか
 *   組み立てた瞬間に合言葉（コミットの短い番号＋組み立てた時刻）を焼き込み、
 *   　・外向きページの見えない札（<meta name="x-build">）
 *   　・/api/version（毎回その場で答える窓口）
 *   の両方から同じ合言葉を出す。**2つが一致していれば、見ているページは最新。**
 *   ずれていたら、それが「配り先が古い」の証拠になる。目で数えなくてよくなる。
 *
 * ■ 中身は公開してよいものだけ
 *   コミットの短い番号と組み立て時刻だけ。鍵・合言葉・環境変数の値は入れない。
 */
const buildStamp = [
  (process.env.VERCEL_GIT_COMMIT_SHA || "").slice(0, 7) || "local",
  new Date().toISOString(),
].join("@");

/**
 * 住所が変わったページの、前の住所から新しい住所への送り先。
 *
 * ★ページの中で送る書き方（redirect()）は、このサイトの作り（全ページを先に
 *   組み立てて配る形）だと **行き先の札が付かない 307 になってしまい、
 *   ブラウザが新しい住所へ移れません**（2026-10-03 に本番で実測）。
 *   ここに書くと配り口が 308 で正しく送るので、必ずここに書くこと。
 */
const permanentMoves = [
  // 「経理まるごと（月5万円前後）」の1枚。
  // 10/3 10:20 に じゅんへ /keiri/plan-draft の住所でお渡ししたあと、
  // 公開して /keiri/plan に移した。お渡しした住所が開けるように送る。
  { source: "/keiri/plan-draft", destination: "/keiri/plan", permanent: true },
];

/** @type {import('next').NextConfig} */
const nextConfig = {
  reactStrictMode: true,
  async redirects() {
    return permanentMoves;
  },
  env: {
    // 公開してよい情報だけを入れる（コミットの短い番号と組み立て時刻）。
    // 名前を NEXT_PUBLIC_ にしてあるのは「ブラウザに配られても構わない」と
    // 一目で分かるようにするため。秘密の値をここに足さないこと。
    NEXT_PUBLIC_BUILD_STAMP: buildStamp,
  },
};

module.exports = nextConfig;
