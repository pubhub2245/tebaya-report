/** 紹介ページに出す質問を、よくある質問（KEIRI_FAQ）から引いて返す */
export function keiriCaseFaq(): Faq[] {
  const found: Faq[] = [];
  for (const q of KEIRI_CASE_FAQ_QUESTIONS) {
    const hit = KEIRI_FAQ.find((f) => f.q === q);
    if (hit) found.push(hit);
  }
  return found;
}
