/**
 * 問い合わせ先（困ったときのページに出す窓口）。
 *
 * ■ 2026-09-20 変更（司令室 kp112）
 *   それまでは環境変数（NEXT_PUBLIC_KEIRI_SUPPORT_EMAIL）が入っているときだけ出し、
 *   無ければ null＝画面は「メールの窓口は準備中です」と出していた。
 *   9/17 にこれを作った時点では、出す宛先が決まっていなかったので正しい作りだった。
 *
 *   **ところが本番では今もこの設定が入っておらず、窓口が「準備中」のままだった。**
 *   いっぽうで同じ宛先（jun@alpha-mj.co.jp）は、
 *   9/18 の じゅんの確定を受けて **特商法のページと紹介ページには載っている**。
 *   ＝ 法律で出すページには宛先が書いてあるのに、
 *     「聞かれたことに答える窓口」（月15,000円に含まれるもの）だけが準備中、
 *     という食い違いが残っていた。払ったお店が最初に困ったとき、行き先が無い。
 *
 *   そこで、設定が無いときは **すでに世に出している連絡先に戻す**ことにした。
 *   ★新しい宛先を作ってはいない。新しく世に出す情報も無い（同じ宛先が2ページに出ている）。
 *   ★別の宛先に分けたくなったら、環境変数を入れればそちらが優先される（作りは残してある）。
 */
export function supportEmail(): string | null {
  const v = (process.env.NEXT_PUBLIC_KEIRI_SUPPORT_EMAIL ?? "").trim();
  if (v !== "") return v;
  // 設定が無いときは、特商法のページに出しているのと同じ連絡先を使う
  return KEIRI_COMPANY.email.trim() === "" ? null : KEIRI_COMPANY.email;
}

