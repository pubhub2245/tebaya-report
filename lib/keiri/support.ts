/** 問い合わせ先。未設定なら null を返す（画面は「準備中」と出す） */
export function supportEmail(): string | null {
  const v = (process.env.NEXT_PUBLIC_KEIRI_SUPPORT_EMAIL ?? "").trim();
  return v === "" ? null : v;
}

