/**
 * 「経理の帳簿が読めなかったとき、画面に何を出すか」を決めるところ
 * （2026-11-05・f1-4）。**計算だけ**（通信もしません・金額を1円も作りません）。
 *
 * ■ なぜ要るのか（やさしい説明）
 *   2026-11-05 18:05 に、倉庫（データのしまい場所）がひとりでに止まりました。
 *   そのとき経理の画面は、赤い帯で「読み込みに失敗しました」と出したうえで、
 *   **そのまま下に数字を出し続ける形**でした。読めなかった中身は空のままなので、
 *   出ていたのは
 *     ・今月の利益 0円
 *     ・今の現金 ＝ 数え始めの残高のまま
 *     ・まだ払っていないお金 0円
 *   という、**ほんとうは1円も確かめていない数字**です。
 *
 *   いちばん高くつくのは、じゅんが金庫を数える1分をここに当ててしまうことです。
 *   数えた金額を、この「作られた現金」と比べると、**大きな差が必ず出ます**。
 *   じゅんはその差の出どころを探し始め、見つからないので
 *   「この道具は合わない」と見ることになります（＝ f1-4 がまちがって不合格になります）。
 *
 *   読めていないときは、**数字をいっさい出さない**のが正しい形です
 *   （lib/keiri/loadMonth.ts が「読めなかった棚を0件と取り違えない」ために
 *   わざと止めているのと、同じ考え方を画面にも通します）。
 *
 * ■ ここでしないこと
 *   ・金額・利益・現金・CSV・試算表・1枚の要約の中身は1円も変えません
 *   ・合否の決め方も変えません
 *   ・鍵・合言葉・倉庫の住所のような値は、1文字も文に入れません
 *     （画面に出す文なので、原因の英語の文そのままは出しません）
 */

/** 読めなかった理由の見分け */
export type KeiriReadFailureKind =
  /** 倉庫そのものにつながらない（眠っている・通信が届かない） */
  | "asleep"
  /** つながったが、帳簿の一部の棚が読めなかった */
  | "shelf"
  /** 合言葉が合わない */
  | "password"
  /** 上のどれとも言えない */
  | "unknown";

export type KeiriReadFailure = {
  kind: KeiriReadFailureKind;
  /** 画面の見出し（1行・やさしい言葉） */
  title: string;
  /** 見出しの下に出す説明（1行ずつ） */
  lines: string[];
  /** ［もう一度ためす］を出すか */
  retry: boolean;
};

/** 倉庫まで届いていないときの言い方（英語のエラー文はそのまま出しません） */
const UNREACHABLE =
  /failed to fetch|fetch failed|networkerror|network error|load failed|econnrefused|enotfound|etimedout|timeout|timed out|socket hang up|service unavailable|bad gateway|gateway timeout|503|502|504/i;

/** 倉庫まで届いていないときの日本語の言い方（こちらで出している文） */
const UNREACHABLE_JA = /つながりません|接続できません|通信できません/;

/** 棚が読めなかったときに、こちらが出している文（lib/keiri/loadMonth.ts） */
const SHELF_JA =
  /読めませんでした|読み取れませんでした|読めていません/;

/**
 * 読めなかった理由を、画面に出す言葉に直す。
 *
 * @param message load() が受け取ったエラーの文（null なら「分からない」扱い）
 */
export function describeKeiriReadFailure(
  message: string | null | undefined,
): KeiriReadFailure {
  const raw = String(message ?? "").trim();

  if (/合言葉/.test(raw)) {
    return {
      kind: "password",
      title: "この画面を開く合言葉が合いませんでした",
      lines: [
        "いったん「ログアウト」して、もう一度 入り直してください。",
        "まちがった金額を出さないために、数字はいっさい出していません。",
      ],
      retry: false,
    };
  }

  if (raw === "" ) {
    return unknownFailure();
  }

  if (UNREACHABLE.test(raw) || UNREACHABLE_JA.test(raw)) {
    return {
      kind: "asleep",
      title: "倉庫（データのしまい場所）に、いまつながりません",
      lines: [
        "お金はかかっていません。無料のしまい場所は、使われない日が続くとひとりでに眠ることがあります。",
        "下の［もう一度ためす］を押してください。それでも同じなら、少し時間をおいてから開き直してください。",
        "金庫を数える1分は、ここが動くようになってからで大丈夫です。いま数えた金額を入れても記録に残らず、比べる相手の金額も作れません。",
        "まちがった金額を出さないために、この画面では数字はいっさい出していません。",
      ],
      retry: true,
    };
  }

  if (SHELF_JA.test(raw)) {
    return {
      kind: "shelf",
      title: "帳簿の一部が、いま読めていません",
      lines: [
        "読めていない所を0円として計算すると、利益も現金もまちがって出ます。だから数字はいっさい出していません。",
        "倉庫（データのしまい場所）が眠っていることもあります。下の［もう一度ためす］を押して、それでも同じなら少し時間をおいてください。",
        "金庫を数える1分は、ここが動くようになってからで大丈夫です。",
      ],
      retry: true,
    };
  }

  return unknownFailure();
}

function unknownFailure(): KeiriReadFailure {
  return {
    kind: "unknown",
    title: "帳簿を読み込めませんでした",
    lines: [
      "下の［もう一度ためす］を押してください。それでも同じなら、少し時間をおいてから開き直してください。",
      "まちがった金額を出さないために、数字はいっさい出していません。",
      "金庫を数える1分は、ここが動くようになってからで大丈夫です。",
    ],
    retry: true,
  };
}

/**
 * 読めなかったときに、数字を出してよいか。
 *
 * **いつでも false** です（読めていないのに数字を出さないため）。
 * 「読めたときだけ出す」を1か所に書いておくための関数で、
 * 画面はこの関数の答えだけを見ます。
 */
export function mayShowKeiriNumbers(message: string | null | undefined): boolean {
  return String(message ?? "").trim() === "";
}

/**
 * 「残そうとしたのに残せなかった」ときの1行を作る（2026-11-05・kp245・f1-4）。
 *
 * ■ なぜ要るのか
 *   いまは倉庫から返ってきた英語の文をそのまま出しています
 *   （例：「記録できませんでした：TypeError: Failed to fetch」）。
 *   じゅんはプログラムを書かない人なので、この文からは
 *   **「自分のやり方が悪いのか」「もう一度 押していいのか」が分かりません。**
 *   倉庫が眠っているだけなら、押し直せば残ります。そこを言葉にします。
 *
 * ★金額は入れません（入れた金額は画面にそのまま残っています）。
 * ★倉庫の住所・鍵・合言葉は1文字も入れません。
 */
export function describeKeiriWriteFailure(
  message: string | null | undefined,
  what = "記録",
): string {
  const raw = String(message ?? "").trim();
  if (UNREACHABLE.test(raw) || UNREACHABLE_JA.test(raw)) {
    return (
      `いま倉庫（データのしまい場所）につながらないので、${what}できませんでした。` +
      "入れた金額はこの画面に残してあります（お金はかかっていません）。" +
      "少し時間をおいて、もう一度 押してください。"
    );
  }
  return `${what}できませんでした：${raw || "理由は返ってきませんでした"}`;
}

/**
 * まだ読み終わっていないあいだ、画面に何を出すか（2026-11-05・f1-4）。
 *
 * ■ なぜ要るのか（2026-11-05 に自分の目で見て分かったこと）
 *   倉庫（データのしまい場所）が眠っているとき、読みに行った返事は
 *   **エラーで返ってくるとは限りません。返ってこないまま待ち続けます。**
 *   そのあいだ画面は「読み込み中…」という小さな1行を出すだけで、
 *   その下に**数字を並べていました**。手元で倉庫に届かない形にして測ったら、
 *   1件も読めていないのに
 *     今月の利益 −35,000円／今の現金 0円／まだ払っていないお金 140,000円
 *   と出ました（どれも既定の決まりだけから作られた数字です）。
 *   じゅんが金庫を数える1分をここに当てると、0円と比べることになります。
 *
 *   ＝ **読み終わるまで数字を出さない**のが正しい形です。
 */
export type KeiriLoadingNotice = {
  title: string;
  lines: string[];
  /** ［もう一度ためす］を出すか（長くかかっているときだけ） */
  retry: boolean;
};

/** 「長くかかっている」と言い始めるまでの時間（ミリ秒） */
export const KEIRI_SLOW_READ_MS = 12000;

export function keiriLoadingNotice(slow: boolean): KeiriLoadingNotice {
  const lines = [
    "読み終わるまで、数字はいっさい出しません（読めていない所を0円として出すと、利益も現金もまちがって見えるためです）。",
  ];
  if (slow) {
    lines.push(
      "少し時間がかかっています。倉庫（データのしまい場所）が眠っているかもしれません（お金はかかっていません）。",
      "金庫を数える1分は、この画面に数字が出てからで大丈夫です。",
    );
  }
  return { title: "帳簿を読み込んでいます…", lines, retry: slow };
}
