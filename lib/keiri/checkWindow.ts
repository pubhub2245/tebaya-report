/**
 * 窓口の返事に必ず足す「いつ・どの版で答えたか」の2つ（2026-10-09・kp246）。
 *
 * ■ なぜ要るか
 *   検査役（B2）が 10/9 に2回つづけて「古い答えが返る」と気づきました。実測すると、
 *   本番の中身は新しい版で動いていて、**外から読む道具が前の答えを手元にためていた**
 *   だけでした。ところが窓口の返事には時刻も版の札も入っていないため、
 *   **検査役はその場で「いま見ているのが新しい答えか」を見分けられません**。
 *   ＝ 本番が正しいのに合否を付けられない、という足止めが起きます。
 *
 * ■ どう直すか
 *   すべての窓口の返事に `build`（版の合言葉）と `answeredAt`（答えを作った時刻）を足します。
 *   ・`build` が本番の版（/api/version）と同じ → その答えは新しい版のもの
 *   ・`answeredAt` が今の時刻から大きく離れている → **読む道具がためた古い答え**
 *   どちらも公開してよい情報だけです（鍵・合言葉・環境変数の値は入れません）。
 */
export type CheckWindowStamp = {
  /** 組み立てたときの合言葉（/api/version の build と見比べる） */
  build: string;
  /** この答えを作った時刻。今の時刻と大きく違えば、読む道具がためた古い答え */
  answeredAt: string;
  /** この時刻を過ぎたら、この答えで合否を付けてはいけない（answeredAt＋10分） */
  verdictValidUntil: string;
  /** 合否に使ってよいかの決まりを1行で（ためこまれた古い答えでも、そのまま読める言葉） */
  verdictRule: string;
  /** 見分け方を1行で（検査役がそのまま読める言葉） */
  freshness: string;
  /**
   * **版がちがって見えたときの読み方**（2026-11-13・B）。
   * 窓口は全部 同じ1つの本番の上で動くので、**版の合言葉はどの窓口も必ず同じ**です。
   * ＝ 窓口の build が /api/version の build と違ったら、それは
   * 「本番の一部だけが古い」ではなく、**読む道具が前の答えをためている**ということです。
   */
  sameBuildEverywhere: string;
};

/**
 * 窓口の返事に「いつ・どの版で答えたか」を足す。※この関数だけが札の形を決める
 *
 * ■ 2026-11-09 に足したこと（kp246・f1-4）
 *   11/9 13:04 に、住所の後ろに `?v=` を付けずに開くと **10月24日の古い答え**が返り、
 *   その古い答えでは金庫の窓口が `ok: true`（＝合格と読める）になっていました。
 *   札（no-store）は前から付けていますが、**外から読む道具が自分の手元にためた分**は
 *   こちらから消せません。そこで**答えそのものに「いつまで合否に使ってよいか」を書く**ことにしました。
 *   ＝ ためこまれた古い答えを読んでも、`verdictValidUntil` を過ぎているので
 *   **そのまま合格にできません**。札に頼らず、答えの中身で守ります。
 *
 * ■ 2026-11-13 に足したこと（f1-4・f3-4・f2-2 の合否を止めないため）
 *   11/13 09:04 に A が「読むだけの窓口のいくつかが、10月13〜25日の答えをそのまま返している」を
 *   行き止まりとして残しました。**本番は古くありませんでした。**
 *   同じ時刻に素の住所（?v= なし）を1本ずつ測ると、6本すべて
 *   版 a5d454d・answeredAt はその場の時刻・配り先は取り置き無し（x-vercel-cache: MISS）・
 *   札も no-store のままでした（2026-11-13 09:3x・curl で実測）。
 *   ＝ 古い答えは **A の読む道具の手元にあったもの**です。
 *   ところが窓口の返事には「版がちがって見えたら、それは読む道具のため込み」と
 *   **どこにも書いていなかった**ので、同じ行き止まりが 11/9・11/10・11/11・11/13 と4回 立ち、
 *   そのたびに最優先の仕事が1つ増えました（4-17 と同じ形）。
 *   窓口は全部 同じ本番の上で動く＝**版はどの窓口も必ず同じ**なので、
 *   その事実を `sameBuildEverywhere` として答えの中に書きます。
 */
export function stampCheckWindow<T>(body: T, now: Date = new Date()): T & CheckWindowStamp {
  const until = new Date(now.getTime() + VERDICT_VALID_MINUTES * 60 * 1000);
  return {
    ...(body as object),
    build: BUILD_STAMP,
    answeredAt: now.toISOString(),
    verdictValidUntil: until.toISOString(),
    verdictRule:
      `いまの時刻が verdictValidUntil（${until.toISOString()}）より後なら、この答えは古いので合否を付けないでください。` +
      "住所の後ろに ?v=いまの時刻 を付けて開き直し、新しい答えで判断してください。",
    freshness:
      "build が /api/version と同じで、answeredAt がいまの時刻なら、この答えは新しい版のものです。answeredAt が古ければ、読む道具が前の答えをためています（住所の後ろに ?v=いまの時刻 を付けて開き直してください）。",
    sameBuildEverywhere:
      "窓口は全部 同じ1つの本番の上で動くので、**版の合言葉（build）はどの窓口も必ず同じ**です。" +
      "いくつかの窓口だけ古い版・古い answeredAt に見えるときは、**本番の一部だけが古いのではありません**" +
      "（そういう形にはなりません）。**それを開いた道具が、前の答えを手元にためている**だけです。" +
      "その場合に直すところはサーバー側にありません。住所の後ろに ?v=いまの時刻 を付けて開き直してください" +
      "（/api/keiri/windows の url には、もう付いています）。",
  } as T & CheckWindowStamp;
}
