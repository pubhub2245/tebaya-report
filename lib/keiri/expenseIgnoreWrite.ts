/**
 * 「同じ支払いなので こちらは数えない」の印を、画面から直すときの決まり
 *                                   （2026-10-21・kp253 ③・f3-3・f3-4）。
 * **計算だけ**（倉庫は触りません）。
 *
 * ■ なぜ要るのか（やさしい説明）
 *   「元に戻す」は、印を消すのではなく**効かなくする**ために、
 *   印の行を1つ**直し**ます（update）。
 *   貼り紙⑫を流すと、印の棚（keiri_expense_ignores）は
 *   「印が空の行だけ 読んでよい」になります。
 *
 *   ここが取り違えやすい所です。倉庫（PostgreSQL）では、
 *   **「どの行を直すか」を選ぶところにも読む決まりが効きます。**
 *   そのため申し込んだお店が「元に戻す」を押すと、
 *   **エラーも出ないまま 0行 だけ直り**、画面は「↩ 元に戻しました」と出ます。
 *   実際には何も戻っていないので、その月の経費は押す前と同じままです。
 *   （2026-10-21 に、同じ形の倉庫＝PostgreSQL 16 で実測しました。
 *     印が付いた行への `update … where` は 0行・`delete … where` も 0行。
 *     手羽屋の行＝印が空 は、今までどおり1行 直せます。）
 *
 * ■ 直し方（この1か所で決める）
 *   ・手羽屋（印が空）… 今までどおり押せる。1文字も変わりません
 *   ・申し込んだお店 … **押す前に止めて、理由を出す。**
 *     「できました」と言わないのが、この経理の土台の決まりです
 *     （CLAUDE.md 5-3／lib/keiri/tenantReportWrite.ts と同じ考え方）。
 *
 * ■ 残っている仕事（やらないことを はっきり書いておく）
 *   申し込んだお店が自分で「元に戻す」を押せるようにするには、
 *   **直すための倉庫の窓口**（読む窓口と対になるもの）が要ります。
 *   いまの貼り紙（⑧⑩⑪⑫）に入っているのは**読む窓口だけ**なので、
 *   ここでは作りません。印を付ける（押して決める）ほうは、
 *   入れるときに印を付けているので今までどおり動きます。
 */

export type IgnoreUndoVerdict = {
  /** 押してよいか */
  allowed: boolean;
  /** 押せないときに画面へ出す1行（押せるときは null） */
  message: string | null;
  why: string;
};

/**
 * 「元に戻す」を押してよいか。
 *
 * ★棚の状態は**聞きません**。締まる前の倉庫なら直せますが、
 *   申し込んだお店が自分の印を直せるのは「貼り紙を流す前」という
 *   短いあいだだけで、そこを頼りにすると、流した日から黙って嘘になります。
 */
export function decideIgnoreUndo(params: { isTebaya: boolean }): IgnoreUndoVerdict {
  if (params.isTebaya) {
    return {
      allowed: true,
      message: null,
      why: "手羽屋（印が空）は締めたあとも直せる＝今までどおり",
    };
  }
  return {
    allowed: false,
    message:
      "この画面からは元に戻せません（倉庫の決まりで、このお店の印はここから直せません）。" +
      "印は消えていませんので、戻したいときはお知らせください。",
    why: "締めたあとは 0行 しか直らず、エラーも出ない＝嘘の「元に戻しました」になるため",
  };
}
