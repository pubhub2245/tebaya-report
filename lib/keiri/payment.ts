/**
 * 「お金をどうやって受け取るか」の言い方を、1か所にまとめたファイル（2026-09-25・kp181）。
 *
 * ■ なぜ作ったか（やさしい説明）
 *   これまで、カードの受付口（Stripe の支払いリンク）がまだ入っていない間は、
 *   紹介ページも特商法のページも「**カード決済は準備中です**」「**お支払いの方法は、
 *   そのときにご案内します**」としか書いていませんでした。
 *   つまり **お金の受け取り方そのものが、どこにも決まっていない** 状態です。
 *
 *   ここが困るのは2つの場面です。
 *     ① 紹介ページを開いた店主が、お金の話の所で「準備中」という字を見る
 *        ＝「この会社、まだ始まっていないのでは」と読まれる
 *     ② 「お願いします」と返事が来たあと、こちらから送るものが1つも無い
 *        ＝ いちばん熱い瞬間に「少々お待ちください」で止まる
 *
 * ■ 直し方（新しい道具は1つも要りません）
 *   **銀行振込**を、カードができるまでの正式なお支払い方法として書きます。
 *   株式会社Alpha の法人口座はすでにあるので、**新しい契約も費用も発生しません**。
 *   お振込先そのものは、このファイルにも画面にも書きません
 *   （公開ページに口座番号を出さず、お申し込みいただいた方へ個別にご案内する形）。
 *
 * ■ カードの受付口が入ったら
 *   `cardLive` が true になった瞬間、自動でカードの書き方に戻ります。
 *   このファイルを誰かが直す必要はありません（legal.ts・offer.ts と同じ作り）。
 *
 * ★ここが唯一の正。画面に文章を直書きしないこと。
 * ★手羽屋の日報・シフト・レジ・LINE・お金の計算には一切さわっていません。
 */

/** カードがまだ使えないあいだの、正式なお支払い方法 */
export const KEIRI_BANK_TRANSFER = "銀行振込" as const;

/**
 * 特商法の「支払方法」の欄に出す1行。
 * ★口座番号はここに書かない（お申し込みのあと、個別にご案内する）。
 */
export function paymentMethodLine(cardLive = false): string {
  return cardLive
    ? "クレジットカード決済（Stripe）"
    : `${KEIRI_BANK_TRANSFER}（お申し込みのあと、担当よりお振込先をご案内します）`;
}

/** 特商法の「支払時期」の欄に出す1行。 */
export function paymentTimingLine(cardLive = false): string {
  return cardLive
    ? "お申し込み時に初回分を決済し、以後は毎月同日に自動で決済されます"
    : "お申し込みの時点ではお支払いは発生しません。ご案内したお振込先へ初回分をお振り込みいただき、以後は毎月お振り込みいただきます";
}

/**
 * 「申し込んでから、使い始めるまで」の②に出す説明。
 * ★「方法はそのときにご案内します」で終わらせない（方法はもう決まっているので、そう書く）。
 */
export function paymentStepBody(cardLive = false): string {
  return cardLive
    ? "そのままカードでお支払いいただけます。お支払いが済んだ時点でお使いいただけます。"
    : "担当からいただいたメールアドレスへご連絡します（通常1営業日以内）。" +
        `お支払いは${KEIRI_BANK_TRANSFER}です。お振込先は、そのときにお伝えします。`;
}

/**
 * 紹介ページの申し込みボタンの下に添える1行（カードがまだ無いとき）。
 * ★「準備中」という言い方をしない。何で払えるかを先に書く。
 */
export function paymentNoticeLine(): string {
  return (
    `お支払いは${KEIRI_BANK_TRANSFER}です（この画面でお支払いは発生しません）。` +
    "お振込先は、お申し込みのあとに担当からご案内します。"
  );
}

/**
 * お申し込みの画面（/keiri/apply）に出す1行。
 *
 * ■ なぜ足したか（2026-09-25・kp184）
 *   kp181 で「準備中」を消したのは**紹介ページと特商法のページだけ**で、
 *   その次に開く **お申し込みの画面** は
 *   「お支払いの方法は、ご連絡のときにご案内します。」のままでした。
 *   ＝ 店主が「申し込む」を押す**直前の1画面だけ**、
 *   受け取り方がまだ決まっていないように読めていた、ということです。
 *   いちばん迷いが出る場所なので、ここにも方法を先に書きます。
 *
 * ★口座番号はここに書かない（お申し込みのあと、個別にご案内する）。
 */
export function paymentApplyLine(cardLive = false): string {
  return cardLive
    ? "お支払いはクレジットカード決済（Stripe）です。お申し込みのあと、決済のご案内をお送りします。"
    : `お支払いは${KEIRI_BANK_TRANSFER}です。お振込先は、お申し込みのあとに担当からご案内します。`;
}

/**
 * お申し込みを受け付けたあとの画面に出す1行。
 * ★「方法もそのときにご案内します」で終わらせない（方法はもう決まっているので、そう書く）。
 */
export function paymentAfterApplyLine(cardLive = false): string {
  return cardLive
    ? "そのご連絡で、カード決済のご案内と、使い始めるための準備をお伝えします。"
    : `そのご連絡で、${KEIRI_BANK_TRANSFER}のお振込先と、使い始めるための準備をお伝えします。`;
}

/**
 * 紹介ページの価格の箱に出す「申し込んでから、使い始めるまで」の1行。
 *
 * ■ なぜ足したか（2026-09-25・kp184）
 *   この1行は **［申し込む］ボタンの真上**、オレンジの箱の中にあります。
 *   店主がいちばん最後に読む所なのに「担当からお支払いの方法をご案内します」と、
 *   方法を言わないままでした（紹介ページの他の所は銀行振込と書いてあるのに）。
 */
export function paymentHandoffLine(cardLive = false): string {
  return cardLive
    ? "申し込みから使い始めまで、人の手は入りません。支払い後すぐに使えます"
    : `お申し込みのあと、担当から${KEIRI_BANK_TRANSFER}のお振込先をご案内します（通常1営業日以内）`;
}
