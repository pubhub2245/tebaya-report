/**
 * 立替（現場）の「最近の10件」を、**読めなかったのに『0件』と出さない**ための決まり
 * （2026-10-19・kp253 ③・f3-4）。**計算だけ**（倉庫は触りません）。
 *
 * ■ なぜ要るのか（やさしい説明）
 *   貼り紙⑫を流すと、立替（現場）の棚は「印が空の行だけ 読んでよい」になります。
 *   よその店がブラウザの公開の鍵でそのまま聞くと、**エラーではなく「0件」**で返ります。
 *   ＝ そのお店が自分で入れた立替が、入れた直後に**黙って消えたように見えます**
 *      （画面は「まだありません」と出る）。入れた人は「保存できなかった」と思い、
 *      もう一度入れて**二重に記録**します（CLAUDE.md 5-4「同じ支払いを2か所に登録しない」に反する）。
 *
 *   ブラウザには合言葉をサーバーのように持たせられないので、ここは
 *   **「0件」と言わずに正直に止まる**のが正しい形です
 *   （lib/keiri/loadMonth.ts・loadMonthServer.ts と同じ考え方）。
 *
 * ■ 手羽屋は1行も変わりません
 *   手羽屋の行は印が空なので、締めたあとも公開の鍵で今までどおり読めます
 *   （貼り紙⑫の下見で実測ずみ）。＝ 手羽屋はいつも今までどおり一覧が出ます。
 *
 * ■ 分からないときは、今までどおり一覧を出す（開かずに閉じない）
 *   貼り紙が流れたかを確かめられなかったときは、**一覧を出す**ほうに倒します。
 *   確かめられないだけで画面を止めると、動いているお店まで止めてしまうためです。
 */

/** 貼り紙⑫（のこりの棚を店ごとに締める）が流れたか */
export type ShelfClosedState =
  /** 流れている＝よその店は公開の鍵で読めない */
  | "締まっている"
  /** まだ流れていない＝今までどおり読める */
  | "まだ"
  /** 確かめられなかった */
  | "分からない";

export type AdvanceReadVerdict = {
  /** 一覧を出してよいか */
  showList: boolean;
  /** 出さないときに画面へ出す1行（出すときは null） */
  message: string | null;
  /** なぜそう決めたか（試験と画面の説明のため） */
  why: string;
};

const CANNOT_READ =
  "いま、このお店の立替の一覧を読めませんでした（通信か、読む道の不調）。" +
  "数字を作らないために、ここでは何も出しません。" +
  "**いま入れた分は記録に残っています**ので、同じものをもう一度 入れないでください。" +
  "少し待ってから開き直してください。";

/**
 * 「最近の10件」を出してよいかを決める。
 *
 * @param isTebaya   手羽屋として開いているか（印が空）
 * @param rows       公開の鍵で読めた行数
 * @param shelfState 貼り紙⑫が流れたか
 */
export function decideAdvanceRead(params: {
  isTebaya: boolean;
  rows: number;
  shelfState: ShelfClosedState;
}): AdvanceReadVerdict {
  const { isTebaya, rows, shelfState } = params;

  // 手羽屋は印が空＝締めても読める。今までどおり出す
  if (isTebaya) {
    return { showList: true, message: null, why: "手羽屋（印が空）は締めても読める" };
  }
  // 1行でも読めていれば、読む道は開いている
  if (rows > 0) {
    return { showList: true, message: null, why: "行が読めている＝読む道は開いている" };
  }
  // よその店で・締まっていて・0件 ＝ 「読めなかった」を「0件」と取り違えてはいけない所
  if (shelfState === "締まっている") {
    return {
      showList: false,
      message: CANNOT_READ,
      why: "よその店・棚は締まっている・0件＝読めなかった（0件と取り違えない）",
    };
  }
  // まだ締まっていない／確かめられない ＝ 今までどおり出す（開かずに閉じない）
  return {
    showList: true,
    message: null,
    why:
      shelfState === "まだ"
        ? "棚がまだ締まっていない＝0件は本当に0件"
        : "締まったか確かめられない＝今までどおり出す",
  };
}
