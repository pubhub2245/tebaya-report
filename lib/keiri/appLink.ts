/**
 * 毎日ひらかれている日報アプリから、経理パッケージのご案内へ行く道（kp200）。
 *
 * ■ なぜ要るか（2026-09-29・司令室 kp200）
 *   受け皿（ご案内ページ → 入力欄 → 控え）は 9/28 に端から端まで通ることを
 *   確かめました。それでもお申し込みが0件なのは、作りではなく
 *   **そのページに来る人がいない**からです（訪問8件はすべて身内か決済会社の画面）。
 *   同じ住所（tebaya-report.vercel.app）の中で毎日必ず開かれている画面は
 *   日報アプリだけなので、そこから1タップで行ける道を1本だけ通します。
 *
 * ■ 直す前に分かっていた事実（正直に書いておく）
 *   日報アプリのホームには、すでに「経理パッケージの紹介ページ →」という
 *   小さな1行が footer にありました。**道が0本だったのではなく、
 *   ①合言葉が付いていない（どの道から来た人か数えられない）
 *   ②行き先が読むところで、入力欄まで行かない
 *   ③管理者ページには1本も無い —— という3つが足りていませんでした。**
 *   この3つを埋めるのがここの仕事です。
 *
 * ■ 決めごと
 *   ・行き先は **ご案内ページの入力欄そのもの**（`/keiri/case?from=app#apply`）。
 *     お試し（trial・kp199）・紙（card・kp193）とまったく同じ形にそろえる。
 *   ・合言葉 `app` は、受け取り側（訪問の記録・お申し込みの控え）で
 *     そのまま数え分けられる（lib/siteVisits.ts の cleanCampaign が1本で掃除する）。
 *   ・値段は lib/keiri/caseNumbers.ts からだけ読む。**ここに金額を書かない。**
 *   ・**日報の入力を邪魔しない。** 置くのは画面のいちばん下だけで、
 *     途中に割り込ませない・画面の下に貼り付けない（帯にしない）。
 *   ・日報・売上のデータは1行も読まない（ただのリンク）。
 *
 * ★ここが唯一の正。画面（app/page.tsx・app/admin/page.tsx）に行き先や文章を
 *   直書きしない。
 */

/** 「毎日の日報アプリから来た」という合言葉。変えるときは tests/keiriAppLink.test.ts も対で直す */
export const APP_FROM_KEY = "app";

/**
 * 日報アプリから申し込みに行く先。
 *
 * 同じサイトの中なので住所は相対（`/keiri/...`）。
 * 末尾の `#apply` が「入力欄まで動く」の部分です。
 */
export const APP_CASE_HREF = `/keiri/case?from=${APP_FROM_KEY}#apply`;

/** 押す所に出す言葉（金額は含めない。金額は下の1行に添える） */
export const APP_LINK_LABEL = "お店の経理をまるごとお任せ";

/** 押す所の右に出す短い言葉 */
export const APP_LINK_ACTION = "ご案内を見る";

/**
 * 押す所のすぐ下に添える1行。
 * 値段は呼ぶ側が caseNumbers.priceLabel() を差し込む（ここに金額を書かない）。
 */
export function appLinkNote(priceLine: string): string {
  return `${priceLine}・この画面でお支払いは発生しません。`;
}

