/**
 * 月次限定商品（monthly_limited_products）を、どのお店のときに読み書きするかの判定。
 *
 * ■ なぜ要るのか（2026-10-24・f3-4）
 *   日報の入力画面は、その月の「限定商品」の名前と単価を**勝手に入れてくれます**
 *   （手羽屋が毎月1つ決めている商品。例「〇〇味 1本 300円」）。
 *   ところがこの棚には「どの店のものか」の欄がまだ無く、読む所も絞っていませんでした。
 *   そのため**よその店が日報を1枚 書くと、手羽屋が決めた商品の名前と単価が
 *   そのお店の売上の内訳に入ってしまいます**：
 *     ・手羽屋の商品の名前と値段が、よその店の画面に出る（見えてはいけないもの）
 *     ・そのお店の売上の内訳に、売っていない商品の行が混ざる（数字が狂う）
 *   棚に欄が無いので絞り込みでは直せません。そこで**手羽屋のときだけ使う**
 *   という門（lib/tenantScope.ts の isTebayaScope と同じ考え方）を掛けます。
 *
 * ■ 手羽屋は1つも変わりません（ここが大事）
 *   手羽屋には印が付きません（印が空＝手羽屋）。印が空のときの答えは「読む・書く」の
 *   そのままなので、いまの画面と1文字も変わりません。
 *
 * ■ ここは倉庫に触りません（純粋な判定だけ。テストで固定するため）
 */

import { isTebayaScope, type TenantScope } from "./tenantScope";

/**
 * その限定商品の棚を、いま読み書きしてよいか。
 *
 * true  … 手羽屋として開いている（印が空）＝今までどおり
 * false … よその店として開いている＝1行も読まない・1行も書かない
 */
export function limitedProductInScope(scope: TenantScope): boolean {
  return isTebayaScope(scope);
}

/**
 * よその店のときに「書き込みを断る」理由の文（画面にそのまま出せる短い1行）。
 *
 * 黙って何もしないと「保存できた」と見えてしまうので、言葉で返します
 * （CLAUDE.md 4-12 の「1行も変わっていなければ『残しました』と言わない」と同じ考え方）。
 */
export const LIMITED_PRODUCT_OUT_OF_SCOPE =
  "この棚は手羽屋のものです（お店ごとの限定商品はまだ扱っていません）";
