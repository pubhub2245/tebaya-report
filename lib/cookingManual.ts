/** マニュアルで使う写真の印（public/supplies/<id>.jpg） */
export function manualPhotoIds(sections: ManualSection[] = COOKING_MANUAL): string[] {
  return sections.flatMap((s) => s.blocks.flatMap((b) => (b.kind === "photos" ? b.items.map((i) => i.id) : [])));
}
