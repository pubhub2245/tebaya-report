/**
 * 「粗利の目安」を出してよいお店かどうかの**決まりだけ**を置いたファイル（2026-10-23・f3-4）。
 *
 * ■ 何が起きていたか（やさしい説明）
 *   日報の確認画面と LINE の報告文には「粗利（現場評価）」が出ます。中身は
 *     原価概算 ＝ 売上の **25%**／場代概算 ＝ 売上の **10%**
 *   で、どちらも **手羽屋の見込みの率**です（lib/money.ts の COST_RATE_FOOD / COST_RATE_RENT。
 *   CLAUDE.md 4-1 に「推定（食材25%・場代10%）」として書かれている手羽屋の決めごと）。
 *   経理パッケージを申し込んだお店（ラーメン屋さんでも美容室でも）が日報を出すと、
 *   **そのお店が1円も決めていない率で「粗利」が出ます**。日当（lib/laborRule.ts）と
 *   出店場所の名寄せ（2026-10-22）で直したのと同じ取り違えです。
 *
 * ■ これからの決まり
 *   ・手羽屋（印が空）… **今までとまったく同じ**。25%・10% の目安を出す
 *   ・よそのお店      … 目安は出さない。代わりに**実際に出たお金だけ**で
 *                       （売上 − 日当 − レジから払った経費）を出す
 *                       ＝ lib/money.ts の calcActualProfit。新しい率を作らない
 *
 * ■ 帳簿の金額は1円も変わりません
 *   ここが決めるのは「画面と文に何を出すか」だけです。日報に保存する金額・
 *   経理（/keiri）の集計・お金の計算（lib/money.ts）には触っていません。
 */

import { normalizeTenantScope, TEBAYA_SCOPE, type TenantScope } from "@/lib/tenantScope";

/**
 * 「粗利の目安（食材25%・場代10%）」を出してよいか。
 * scope を渡さないときは手羽屋として扱う＝**今までと同じ答え（出す）**。
 */
export function showsEstimatedGrossProfit(
  scope: TenantScope = TEBAYA_SCOPE,
): boolean {
  return !normalizeTenantScope(scope);
}

/** よそのお店の画面・文に添える1行（なぜ目安が出ていないか） */
export const ACTUAL_ONLY_NOTE =
  "粗利の目安（食材25%・場代10%）は手羽屋の決めごとなので、このお店では出していません。" +
  "下は実際に出たお金（日当・レジから払った経費）だけで計算した粗利です。";
